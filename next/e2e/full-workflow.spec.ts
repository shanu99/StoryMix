import {test,expect} from '@playwright/test'
import {join} from 'node:path'
import {readFileSync} from 'node:fs'
import {execFileSync} from 'node:child_process'

test('complete mixed project: import 3 kinds, edit, save, reload, relink and export playable MP4',async({page})=>{
 test.setTimeout(180000)
 const media=(name:string)=>join(process.cwd(),'e2e','fixtures',name)
 await page.goto('/')
 const input=page.locator('input[aria-label="Choose video audio or image files"]')
 await input.setInputFiles(media('test-video.mp4'))
 await expect(page.getByText('This video has audio')).toBeVisible({timeout:20000})
 await page.getByText('Video + Audio',{exact:true}).click()
 await expect(page.getByText(/Imported 1 files/)).toBeVisible()
 await input.setInputFiles(media('test-audio.wav'))
 await expect(page.getByText(/Imported 1 files/)).toBeVisible()
 await input.setInputFiles(media('test-image.png'))
 await expect(page.getByText(/Imported 1 files/)).toBeVisible()
 await expect(page.locator('[data-clip-type="video"]')).toHaveCount(1)
 await expect(page.locator('[data-clip-type="image"]')).toHaveCount(1)
 expect(await page.locator('[data-clip-type="audio"]').count()).toBeGreaterThanOrEqual(2)
 const clip=page.locator('[data-clip-type="video"]').first()
 await clip.click({position:{x:40,y:14}})
 await page.getByRole('spinbutton',{name:'Scale'}).fill('0.85')
 await page.getByRole('spinbutton',{name:'Rotate (°)'}).fill('7')
 const sound=page.locator('[data-clip-type="audio"]').first()
 await sound.click({position:{x:30,y:12}})
 await page.getByRole('spinbutton',{name:'Fade in (sec)'}).fill('0.4')
 await page.getByRole('spinbutton',{name:'Fade out (sec)'}).fill('0.4')
 await page.locator('.sm-top-menu').first().locator('summary').click()
 const savedPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'Save project'}).click()
 const projectPath=await (await savedPromise).path()
 const document=JSON.parse(readFileSync(projectPath!,'utf8'))
 const clips=(Object.values(document.clips).flat() as Array<{type:string;audio?:{fadeInSec?:number}}>)
 for(const kind of ['video','audio','image'])expect(clips.some(c=>c.type===kind),kind).toBeTruthy()
 expect(clips.some(c=>c.audio?.fadeInSec===.4)).toBeTruthy()
 await page.reload()
 await page.locator('input[accept=".json"]').setInputFiles(projectPath!)
 await expect(page.getByText(/Project loaded. Relink 3 local media files/)).toBeVisible({timeout:15000})
 await page.locator('input[aria-label="Relink original media files"]').setInputFiles([media('test-video.mp4'),media('test-audio.wav'),media('test-image.png')])
 if(await page.getByText('This video has audio').isVisible({timeout:3000}).catch(()=>false))await page.getByText('Video only',{exact:true}).click()
 await expect(page.getByText(/Relinked [3-9][0-9]* clips/)).toBeVisible({timeout:25000})
 await expect(page.getByRole('button',{name:'Relink (3)'})).toHaveCount(0)
 await page.locator('.elah-export-btn').click()
 await page.getByRole('button',{name:/360p/}).click()
 const outputPromise=page.waitForEvent('download',{timeout:125000})
 await page.getByRole('button',{name:'Export',exact:true}).last().click()
 const output=await outputPromise
 const outputPath=await output.path()
 const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json',outputPath!],{encoding:'utf8'}))
 expect(probe.streams.find((s:any)=>s.codec_type==='video')?.codec_name).toBe('h264')
 expect(probe.streams.find((s:any)=>s.codec_type==='audio')?.codec_name).toBe('aac')
 expect(Number(probe.format.duration)).toBeGreaterThan(5)
})
