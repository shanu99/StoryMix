import {test,expect} from '@playwright/test'
import {join} from 'node:path'

test('real clip transform, undo/redo, speed, split and deletion',async({page})=>{
 await page.goto('/')
 await page.locator('input[aria-label="Choose video audio or image files"]').setInputFiles(join(process.cwd(),'e2e','fixtures','test-video.mp4'))
 await expect(page.getByText('This video has audio')).toBeVisible()
 await page.getByText('Video only',{exact:true}).click()
 await expect(page.getByText(/placed 1 clips/)).toBeVisible()
 const clip=page.locator('[data-clip-type="video"]').first()
 await clip.click({position:{x:35,y:20}})
 await expect(clip).toHaveAttribute('data-selected','true')
 const scale=page.getByRole('spinbutton',{name:'Scale'})
 await expect(scale).toHaveValue('1')
 await scale.fill('1.2')
 await expect(scale).toHaveValue('1.2')
 await page.getByRole('button',{name:'Undo'}).click()
 await expect(scale).toHaveValue('1')
 await page.getByRole('button',{name:'Redo'}).click()
 await expect(scale).toHaveValue('1.2')
 await page.getByRole('spinbutton',{name:'Volume (%)'}).fill('80')
 await expect(page.getByRole('spinbutton',{name:'Volume (%)'})).toHaveValue('80')
 await page.getByRole('spinbutton',{name:'Speed (×)'}).fill('1.5')
 await expect(page.getByRole('spinbutton',{name:'Speed (×)'})).toHaveValue('1.5')
 await page.getByRole('spinbutton',{name:'Speed (×)'}).fill('1')
 await page.getByRole('textbox',{name:'Seek timecode'}).fill('00:00:01:00')
  await page.getByRole('textbox',{name:'Seek timecode'}).press('Enter')
 await page.getByRole('button',{name:'Split',exact:true}).click()
 await expect(page.locator('[data-clip-type="video"]')).toHaveCount(2)
})
