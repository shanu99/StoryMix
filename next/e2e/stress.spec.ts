import {test,expect,Page} from '@playwright/test'
import {join} from 'node:path'
import {execFileSync} from 'node:child_process'
import {readFileSync} from 'node:fs'
const fixture=(name:string)=>join(process.cwd(),'e2e','fixtures',name)
async function save(page:Page){
 const menu=page.locator('.sm-top-menu').first()
 if((await menu.getAttribute('open'))===null)await menu.locator('summary').click()
 const event=page.waitForEvent('download')
 await page.getByRole('button',{name:'Save project'}).click()
 return (await event).path()
}
test('1080p H264/AAC real 3-second video export passes ffprobe resolution/codec gate',async({page})=>{
 test.setTimeout(300000)
 await page.goto('/')
 await page.locator('input[aria-label="Choose video audio or image files"]').setInputFiles(fixture('test-hd.mp4'))
 await expect(page.getByText('This video has audio')).toBeVisible({timeout:35000})
 await page.getByText('Video + Audio',{exact:true}).click()
 await expect(page.getByText(/Imported 1 files/)).toBeVisible({timeout:45000})
 await page.locator('.elah-export-btn').click()
 await page.getByRole('button',{name:/1080p/}).click()
 const event=page.waitForEvent('download',{timeout:260000})
 await page.getByRole('button',{name:'Export',exact:true}).last().click()
 const dl=await event
 const path=await dl.path()
 const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json',path!],{encoding:'utf8'}))
 const video=probe.streams.find((s:any)=>s.codec_type==='video')
 const audio=probe.streams.find((s:any)=>s.codec_type==='audio')
 expect(video?.codec_name).toBe('h264')
 expect(video?.height).toBe(1080)
 expect(audio?.codec_name).toBe('aac')
 expect(Number(probe.format.duration)).toBeGreaterThan(2.5)
 console.log('1080p export:',{width:video.width,height:video.height,codec:video.codec_name,audio:audio.codec_name,duration:probe.format.duration})
})
test('five-minute video: import, seek, save, reload and relink without crashes',async({page})=>{
 test.setTimeout(240000)
 const errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.locator('input[aria-label="Choose video audio or image files"]').setInputFiles(fixture('test-five-minute.mp4'))
 await expect(page.getByText('This video has audio')).toBeVisible({timeout:40000})
 await page.getByText('Video only',{exact:true}).click()
 await expect(page.getByText(/Imported 1 files/)).toBeVisible({timeout:40000})
 const seek=page.getByRole('textbox',{name:'Seek timecode'})
 await seek.fill('00:04:45:00');await seek.press('Enter')
 await expect(seek).toHaveValue('00:04:45:00')
 const projectPath=await save(page)
 expect(projectPath).toBeTruthy()
 const project=JSON.parse(readFileSync(projectPath!,'utf8'))
 const video=(Object.values(project.clips).flat() as any[]).find(c=>c.type==='video')
 expect(video.durationFrames).toBeGreaterThanOrEqual(8900)
 await page.reload()
 await page.locator('input[accept=".json"]').setInputFiles(projectPath!)
 await expect(page.getByText(/Project loaded/)).toBeVisible({timeout:25000})
 await page.locator('input[aria-label="Relink original media files"]').setInputFiles(fixture('test-five-minute.mp4'))
 await expect(page.getByText(/Relinked [1-9]/)).toBeVisible({timeout:35000})
 await seek.fill('00:04:30:00');await seek.press('Enter')
 await expect(seek).toHaveValue('00:04:30:00')
 expect(errors).toEqual([])
})
